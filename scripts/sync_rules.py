#!/usr/bin/env python3
"""Write overlay/common/lib/web_product/web_rules_data.dart from the apps' own how-to-play catalogues.

    python3 scripts/sync_rules.py --apps <folder with checkouts named game-mind-1, game-mind-9, game-craft-preteen, ...>

Sources (the single place the apps keep the text, kept word for word in each app's docs/SPEC.md):
- Mind hubs: lib/core/rules/game_rules.dart   (GameRules(id:, title:, rules: [...], tips: [...]))
- Craft apps: lib/engine/minigames/how_to_play_catalogue.dart   (HowToPlay('id', 'title', [rules], [tips]))
The three Craft catalogues are identical; the first one found is used. Run this after the apps' text changes, commit the
generated file, and the pin push deploys it. Nothing is hand-edited in the generated file.
"""
import argparse
import re
import sys
from pathlib import Path

STR = re.compile(r"'((?:[^'\\]|\\.)*)'")


def unescape(s):
    return re.sub(r"\\(.)", lambda m: {"n": "\n"}.get(m.group(1), m.group(1)), s)


def strings(chunk):
    return [unescape(m.group(1)) for m in STR.finditer(chunk)]


def match_bracket(text, start):
    """Index of the ']' that closes the '[' at text[start]."""
    depth, i, n = 0, start, len(text)
    in_str = False
    while i < n:
        c = text[i]
        if in_str:
            if c == "\\":
                i += 1
            elif c == "'":
                in_str = False
        elif c == "'":
            in_str = True
        elif c == "[":
            depth += 1
        elif c == "]":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    raise ValueError("unbalanced bracket")


def list_after(text, label):
    i = text.index(label)
    a = text.index("[", i)
    b = match_bracket(text, a)
    return strings(text[a:b + 1]), b + 1


def parse_hub(src):
    out = {}
    for m in re.finditer(r"GameRules\(\s*id:\s*'([^']+)',\s*title:\s*'((?:[^'\\]|\\.)*)',", src):
        rules, end = list_after(src[m.end():], "rules:")
        tips, _ = list_after(src[m.end() + end:], "tips:")
        out[m.group(1)] = (unescape(m.group(2)), rules, tips)
    return out


def parse_craft(src):
    out = {}
    for m in re.finditer(r"HowToPlay\(\s*'([^']+)',\s*'((?:[^'\\]|\\.)*)',", src):
        a = src.index("[", m.end())
        b = match_bracket(src, a)
        rules = strings(src[a:b + 1])
        a2 = src.index("[", b)
        b2 = match_bracket(src, a2)
        out[m.group(1)] = (unescape(m.group(2)), rules, strings(src[a2:b2 + 1]))
    return out


def dart(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n") + "'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apps", required=True)
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "overlay/common/lib/web_product/web_rules_data.dart"))
    a = ap.parse_args()
    apps = Path(a.apps)
    merged, srcs = {}, []
    for hub in ("game-mind-1", "game-mind-9"):
        f = apps / hub / "lib/core/rules/game_rules.dart"
        if f.exists():
            merged.update(parse_hub(f.read_text()))
            srcs.append(f"{hub}")
    for craft in ("game-craft-preteen", "game-craft-lowteen", "game-craft_highteen"):
        f = apps / craft / "lib/engine/minigames/how_to_play_catalogue.dart"
        if f.exists():
            merged.update({k: v for k, v in parse_craft(f.read_text()).items() if k not in merged})
            srcs.append(f"{craft}")
            break
    if not merged:
        sys.exit("no catalogues found")
    lines = ["// GENERATED by scripts/sync_rules.py from the apps' how-to-play catalogues (" + ", ".join(srcs) + ").",
             "// Do not edit by hand: change the text in the app, run the script, commit this file.",
             "import 'web_rules_model.dart';", "", "const Map<String, GameRules> webRulesData = {"]
    for gid in merged:
        title, rules, tips = merged[gid]
        lines.append(f"  {dart(gid)}: GameRules({dart(title)}, [")
        lines += [f"    {dart(r)}," for r in rules]
        lines.append("  ], [")
        lines += [f"    {dart(t)}," for t in tips]
        lines.append("  ]),")
    lines.append("};")
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(f"{len(merged)} games -> {a.out}")


if __name__ == "__main__":
    main()
